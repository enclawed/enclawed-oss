// The vendor attestation roots a device-bound platform passkey must chain to,
// pinned in the repository. Each entry names where it was downloaded from and
// its SHA-256 fingerprint (of the DER certificate); a root whose PEM does not
// match its fingerprint is never trusted, so an edited PEM refuses every
// registration of that format instead of trusting a different root.
//
// Downloaded 2026-11-23:
//   - Microsoft TPM Root Certificate Authority 2014: the root of the
//     attestation identity key (AIK) certificates Windows issues for TPMs,
//     which sign Windows Hello's "tpm" attestations.
//   - Apple WebAuthn Root CA: the root of Apple's "apple" attestations.
//   - Google's hardware attestation roots (the JSON list at
//     https://android.googleapis.com/attestation/root): an RSA-4096 root and
//     the EC P-384 "Key Attestation CA1" root, for "android-key" attestations.

