/** A pinned root's certificate, or null when its PEM does not match its fingerprint or is not a CA. */
export function loadPinnedRoot(r: PinnedRoot): X509Certificate | null {
  try {
    const cert = new X509Certificate(r.pem);
    const fp = createHash("sha256").update(cert.raw).digest("hex");
    return fp === r.sha256 && cert.ca ? cert : null;
  } catch {
    return null;
  }
}

/** The pinned roots of a format that match their fingerprints. */
export function pinnedRoots(fmt: PlatformAttestationFormat): X509Certificate[] {
  return PINNED_ATTESTATION_ROOTS[fmt]
    .map(loadPinnedRoot)
    .filter((c): c is X509Certificate => c !== null);
}
