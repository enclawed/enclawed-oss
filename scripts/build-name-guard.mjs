#!/usr/bin/env node
// Prebuild the containment name guard (src/enclawed/containment/name-guard.c)
// as static Linux binaries for x64 and arm64, so an installed package never
// needs a C compiler. Each binary's SHA-256 is written into
// src/enclawed/prebuilt/name-guard.generated.ts, which the build
// bundles into the JS; the containment verifies the binary against that
// digest before every exec (a digest file next to the binary could be
// replaced with it).
//
//   node scripts/build-name-guard.mjs            build what this host can
//   node scripts/build-name-guard.mjs --check    exit 1 when a binary or the
//                                                 recorded digests are stale
//
// Toolchains, in order: `zig cc -target <arch>-linux-musl` (both arches from
// any host), a musl cross gcc (`<arch>-linux-musl-gcc`), then the host's own
// `gcc -static` for the host arch only. An arch no toolchain here can build
// keeps its previous binary and digest; build it on a machine of that arch
// (or with zig) with this same script.

import { execFileSync, spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
// --source FILE builds from another copy (e.g. the committed one, `git show HEAD:...`).
const srcArg = process.argv.indexOf("--source");
const SRC =
  srcArg >= 0
    ? path.resolve(process.argv[srcArg + 1])
    : path.join(root, "src", "enclawed", "containment", "name-guard.c");
const OUT = path.join(root, "prebuilt", "name-guard");
const GEN = path.join(root, "src", "enclawed", "prebuilt", "name-guard.generated.ts");
const ARCHES = { x64: "x86_64", arm64: "aarch64" };
const FLAGS = ["-O2", "-Wall", "-static", "-s"];

const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");
const has = (cmd) =>
  spawnSync("sh", ["-c", `command -v ${cmd}`], { encoding: "utf8" }).status === 0;

function readRecorded() {
  try {
    const text = fs.readFileSync(GEN, "utf8");
    const src = /sourceSha256: "([0-9a-f]{64})"/.exec(text)?.[1] ?? null;
    const bins = {};
    for (const arch of Object.keys(ARCHES)) {
      const m = new RegExp(`"linux-${arch}": "([0-9a-f]{64})"`).exec(text);
      bins[arch] = m ? m[1] : null;
    }
    return { src, bins };
  } catch {
    return { src: null, bins: {} };
  }
}

/** The compiler command for one arch, or null when none here can build it. */
function compilerFor(arch) {
  const triple = ARCHES[arch];
  if (has("zig")) {
    return { cmd: "zig", args: ["cc", "-target", `${triple}-linux-musl`] };
  }
  if (has(`${triple}-linux-musl-gcc`)) {
    return { cmd: `${triple}-linux-musl-gcc`, args: [] };
  }
  const hostArch = os.arch();
  if (arch === hostArch && process.platform === "linux") {
    for (const cc of ["musl-gcc", "gcc", "cc"]) {
      if (has(cc)) {
        return { cmd: cc, args: [] };
      }
    }
  }
  return null;
}

function write(src, bins) {
  const entries = Object.keys(ARCHES)
    .map((a) => `  "linux-${a}": ${bins[a] ? `"${bins[a]}"` : "null"},`)
    .join("\n");
  fs.writeFileSync(
    GEN,
    `// Generated by scripts/build-name-guard.mjs: do not edit.\n` +
      `// The SHA-256 of each prebuilt name guard (prebuilt/name-guard/linux-<arch>/name-guard),\n` +
      `// bundled into the JS so the binary is checked against a digest it cannot replace.\n\n` +
      `export const NAME_GUARD_PREBUILT = {\n` +
      `  sourceSha256: "${src}",\n` +
      `  binaries: {\n${entries
        .split("\n")
        .map((l) => `  ${l}`)
        .join("\n")}\n  },\n} as const;\n`,
  );
}

const check = process.argv.includes("--check");
const source = fs.readFileSync(SRC);
const srcDigest = sha256(source);
const recorded = readRecorded();

if (check) {
  const problems = [];
  if (recorded.src !== srcDigest) {
    problems.push(
      `the prebuilt name guard was built from another name-guard.c (recorded ${recorded.src}, now ${srcDigest}): run node scripts/build-name-guard.mjs`,
    );
  }
  for (const arch of Object.keys(ARCHES)) {
    const f = path.join(OUT, `linux-${arch}`, "name-guard");
    const want = recorded.bins[arch];
    if (!want) {
      problems.push(`no prebuilt name guard for linux-${arch}`);
    } else if (!fs.existsSync(f) || sha256(fs.readFileSync(f)) !== want) {
      problems.push(
        `prebuilt/name-guard/linux-${arch}/name-guard does not match its recorded digest`,
      );
    }
  }
  for (const p of problems) {
    console.error(`build-name-guard: ${p}`);
  }
  process.exit(problems.length ? 1 : 0);
}

const bins = { ...recorded.bins };
const built = [];
for (const arch of Object.keys(ARCHES)) {
  const c = compilerFor(arch);
  if (!c) {
    console.warn(
      `build-name-guard: no toolchain here builds linux-${arch} (install zig, or run this script on a linux-${arch} machine); keeping its previous binary`,
    );
    // A binary built from an older source is not kept as if it were current.
    if (recorded.src !== srcDigest) {
      bins[arch] = null;
    }
    continue;
  }
  const dir = path.join(OUT, `linux-${arch}`);
  fs.mkdirSync(dir, { recursive: true });
  const out = path.join(dir, "name-guard");
  execFileSync(c.cmd, c.args.concat(FLAGS, ["-o", out, SRC]), {
    stdio: ["ignore", "inherit", "inherit"],
    env: { PATH: process.env.PATH ?? "/usr/bin:/bin", LC_ALL: "C" },
  });
  fs.chmodSync(out, 0o555);
  bins[arch] = sha256(fs.readFileSync(out));
  built.push(`linux-${arch} (${path.basename(c.cmd)})`);
}
write(srcDigest, bins);
console.log(
  `build-name-guard: built ${built.join(", ") || "nothing"}; digests in ${path.relative(root, GEN)}`,
);
