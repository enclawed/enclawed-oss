#!/usr/bin/env node
// Regenerate src/enclawed/auth/attestation-roots-packed.ts from the FIDO
// Alliance Metadata Service (MDS3) blob.
//
//   curl -sSL -o mds.jwt https://mds3.fidoalliance.org/
//   curl -sS -o root-r3.crt https://secure.globalsign.com/cacert/root-r3.crt
//   node scripts/enclawed/gen-packed-attestation-roots.mjs mds.jwt root-r3.crt
//
// The blob is a JWT whose x5c chain must end at GlobalSign Root CA - R3 (the
// FIDO MDS root), pinned here by its SHA-256 fingerprint; its RS256 signature
// must verify with the chain's leaf. Selected: FIDO2 authenticators of the
// curated hardware security key vendors whose metadata says
//   - FIDO certified, and no status report of REVOKED or a compromise
//     (attestation key, user verification bypass, user key remote/physical),
//   - keyProtection hardware AND secure_element,
//   - attachmentHint external (a security key, not a platform authenticator),
//   - attestationTypes basic_full (a packed attestation with x5c),
// each with the CA certificates its attestation chains to (a trust anchor
// that is not a CA certificate is left out, and a model left with none is
// left out).

import { X509Certificate, createHash, createVerify } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const GLOBALSIGN_R3_SHA256 = "cbb522d7b7f127ad6a0113865bdf1cd4102e7d0759af635a7cf4720dc963c53b";
const VENDORS = /yubi|titan|feitian|solo|nitrokey|thales|safenet|\bhid\b|token2|onespan/i;
const BAD = new Set([
  "REVOKED",
  "ATTESTATION_KEY_COMPROMISE",
  "USER_VERIFICATION_BYPASS",
  "USER_KEY_REMOTE_COMPROMISE",
  "USER_KEY_PHYSICAL_COMPROMISE",
]);

const [blobPath, rootPath] = process.argv.slice(2);
if (!blobPath || !rootPath) {
  console.error("usage: gen-packed-attestation-roots.mjs <mds3.jwt> <globalsign-root-r3.crt>");
  process.exit(2);
}
const fp = (c) => createHash("sha256").update(c.raw).digest("hex");
const root = new X509Certificate(fs.readFileSync(rootPath));
if (fp(root) !== GLOBALSIGN_R3_SHA256) {
  throw new Error("the given root is not GlobalSign Root CA - R3");
}
const jwt = fs.readFileSync(blobPath, "utf8").trim();
const [h, p, s] = jwt.split(".");
const header = JSON.parse(Buffer.from(h, "base64url").toString("utf8"));
const chain = header.x5c.map((c) => new X509Certificate(Buffer.from(c, "base64")));
const now = Date.now();
chain.forEach((c, i) => {
  const issuer = chain[i + 1] ?? root;
  if (!c.checkIssued(issuer) || !c.verify(issuer.publicKey)) {
    throw new Error(`MDS chain certificate ${i} does not verify`);
  }
  if (now < Date.parse(c.validFrom) || now > Date.parse(c.validTo)) {
    throw new Error(`MDS chain certificate ${i} is outside its validity`);
  }
});
if (header.alg !== "RS256") {
  throw new Error(`unexpected MDS blob algorithm ${header.alg}`);
}
const v = createVerify("RSA-SHA256");
v.update(`${h}.${p}`);
if (!v.verify(chain[0].publicKey, Buffer.from(s, "base64url"))) {
  throw new Error("the MDS blob signature does not verify");
}
const body = JSON.parse(Buffer.from(p, "base64url").toString("utf8"));

const roots = new Map();
const models = [];
for (const e of body.entries) {
  const m = e.metadataStatement;
  if (!m || !e.aaguid || m.protocolFamily !== "fido2" || !VENDORS.test(m.description)) {
    continue;
  }
  const st = (e.statusReports ?? []).map((r) => r.status);
  if (!st.some((x) => x.startsWith("FIDO_CERTIFIED")) || st.some((x) => BAD.has(x))) {
    continue;
  }
  const kp = m.keyProtection ?? [];
  if (!kp.includes("hardware") || !kp.includes("secure_element")) {
    continue;
  }
  if (
    !(m.attachmentHint ?? []).includes("external") ||
    !(m.attestationTypes ?? []).includes("basic_full")
  ) {
    continue;
  }
  const anchors = new Set();
  for (const b64 of m.attestationRootCertificates ?? []) {
    const c = new X509Certificate(Buffer.from(b64, "base64"));
    if (!c.ca) {
      continue;
    }
    const f = fp(c);
    roots.set(f, { sha256: f, name: c.subject.replace(/\n/g, ", "), der: c.raw });
    anchors.add(f);
  }
  if (anchors.size > 0) {
    models.push({
      aaguid: e.aaguid.toLowerCase(),
      description: m.description,
      roots: [...anchors].toSorted((a, b) => (a < b ? -1 : a > b ? 1 : 0)),
    });
  }
}
models.sort((a, b) => (a.aaguid < b.aaguid ? -1 : a.aaguid > b.aaguid ? 1 : 0));
const rootList = [...roots.values()].toSorted((a, b) => (a.sha256 < b.sha256 ? -1 : 1));

const pem = (der) =>
  `-----BEGIN CERTIFICATE-----\n${der
    .toString("base64")
    .match(/.{1,64}/g)
    .join("\n")}\n-----END CERTIFICATE-----`;
const date = new Date().toISOString().slice(0, 10);
const out = `// GENERATED by scripts/enclawed/gen-packed-attestation-roots.mjs; do not edit.
//
// The hardware security keys whose "packed" attestation enrollment accepts:
// each model's AAGUID and the CA certificates its attestation must chain to.
// Source: the FIDO Alliance Metadata Service blob https://mds3.fidoalliance.org/
// (no. ${body.no}, fetched ${date}, next update ${body.nextUpdate}), its signature
// verified with its x5c chain up to GlobalSign Root CA - R3 (SHA-256
// ${GLOBALSIGN_R3_SHA256}). Selection rule: the header of the
// generator. ${models.length} models, ${rootList.length} CA certificates.

import type { PinnedRoot } from "./attestation-roots.js";

export type PackedModel = Readonly<{ aaguid: string; description: string; roots: readonly string[] }>;

export const MDS_SOURCE = ${JSON.stringify({ url: "https://mds3.fidoalliance.org/", no: body.no, fetched: date })} as const;

export const PACKED_HARDWARE_ROOTS: readonly PinnedRoot[] = [
${rootList
  .map(
    (r) => `  {
    name: ${JSON.stringify(r.name)},
    source: "FIDO MDS3 blob no. ${body.no}",
    sha256: "${r.sha256}",
    pem: \`${pem(r.der)}\`,
  },`,
  )
  .join("\n")}
];

export const PACKED_HARDWARE_MODELS: readonly PackedModel[] = [
${models
  .map(
    (m) =>
      `  { aaguid: "${m.aaguid}", description: ${JSON.stringify(m.description)}, roots: [${m.roots.map((x) => `"${x}"`).join(", ")}] },`,
  )
  .join("\n")}
];
`;
const target = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "../../src/enclawed/auth/attestation-roots-packed.ts",
);
fs.writeFileSync(target, out);
console.error(`wrote ${target}: ${models.length} models, ${rootList.length} roots`);
